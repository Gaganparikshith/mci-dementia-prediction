def main():
    df = load_data()

    coverage = compute_feature_coverage(df)

    df, clinical_features, volume_features = select_valid_features(
        df,
        coverage,
    )

    x_train, x_test, y_train, y_test, all_features, clinical_indices, volume_indices = (
        create_shared_split(
            df,
            clinical_features,
            volume_features,
        )
    )

    model_configs = build_model_configs(
        all_features,
        clinical_features,
        volume_features,
        clinical_indices,
        volume_indices,
    )

    trained_models, test_probabilities, test_metrics = train_models(
        x_train,
        x_test,
        y_train,
        y_test,
        model_configs,
    )

    save_bootstrap_results(
        y_test,
        test_probabilities,
        model_configs,
    )

    save_comparison_table(
        test_metrics,
        model_configs,
    )

    save_roc_pr_curves(
        y_test,
        test_probabilities,
        test_metrics,
        model_configs,
    )

    save_shap_importance(
        x_test,
        trained_models,
        model_configs,
    )

    save_model_comparison_bar(
        test_metrics,
        model_configs,
    )

    print_final_summary(
        test_metrics,
        model_configs,
    )


if __name__ == "__main__":
    main()