def compute_feature_coverage(df):
    coverage = {}

    for feature in E4_CLINICAL_FEATURES + MRI_VOLUME_CANDIDATES:
        if feature in df.columns:
            coverage[feature] = df[feature].notna().sum() / len(df)
        else:
            coverage[feature] = 0.0

    return coverage


def select_valid_features(df, coverage):
    clinical_features = [
        feature
        for feature in E4_CLINICAL_FEATURES
        if feature in df.columns and coverage[feature] >= SPARSE_THRESHOLD
    ]

    volume_features = [
        feature
        for feature in MRI_VOLUME_CANDIDATES
        if feature in df.columns and coverage[feature] >= SPARSE_THRESHOLD
    ]

    print(f"\n  Clinical features valid   : {len(clinical_features)} / {len(E4_CLINICAL_FEATURES)}")
    print(f"  Volumetric features valid : {len(volume_features)} / {len(MRI_VOLUME_CANDIDATES)}")

    if not volume_features:
        print()
        print("  WARNING: No MRI volumetric features have >=10% coverage.")
        print("  Models B and C will run using placeholder columns.")
        print("  Results will not be meaningful until real volume data is available.")
        print()

        placeholder_features = [
            "Hippocampus_total",
            "Hippocampus_ICV_ratio",
            "ICV",
            "Ventricles",
        ]

        for feature in placeholder_features:
            if feature not in df.columns:
                df[feature] = np.nan

        volume_features = placeholder_features

        print(f"  Using placeholder volume columns: {placeholder_features}")

    return df, clinical_features, volume_features


def create_shared_split(df, clinical_features, volume_features):
    section("STEP 1 - Stratified 80/20 split")

    all_features = sorted(set(clinical_features + volume_features))

    x_all = df[all_features].values
    y = df["LABEL"].values

    x_train, x_test, y_train, y_test = train_test_split(
        x_all,
        y,
        test_size=0.20,
        stratify=y,
        random_state=RANDOM_STATE,
    )

    print(f"  Train: {len(y_train)}  |  Test: {len(y_test)}")

    feature_index = {
        feature: index
        for index, feature in enumerate(all_features)
    }

    clinical_indices = [
        feature_index[feature]
        for feature in clinical_features
        if feature in feature_index
    ]

    volume_indices = [
        feature_index[feature]
        for feature in volume_features
        if feature in feature_index
    ]

    print(f"  Clinical feature indices  : {len(clinical_indices)}")
    print(f"  Volumetric feature indices: {len(volume_indices)}")

    return x_train, x_test, y_train, y_test, all_features, clinical_indices, volume_indices


def build_model_configs(all_features, clinical_features, volume_features, clinical_indices, volume_indices):
    return {
        "A_clinical": {
            "indices": clinical_indices,
            "features": clinical_features,
            "label": MODEL_LABELS["A_clinical"],
        },
        "B_volumes": {
            "indices": volume_indices,
            "features": volume_features,
            "label": MODEL_LABELS["B_volumes"],
        },
        "C_combined": {
            "indices": list(range(len(all_features))),
            "features": all_features,
            "label": MODEL_LABELS["C_combined"],
        },
    }


def train_models(x_train, x_test, y_train, y_test, model_configs):
    section("STEP 2 - Training models")

    trained_models = {}
    test_probabilities = {}
    test_metrics = {}

    for model_key, config in model_configs.items():
        feature_indices = config["indices"]
        feature_names = config["features"]
        model_label = config["label"]

        print(f"\n  -- {model_label}")

        if not feature_indices:
            print("    SKIP: no valid features")
            continue

        x_train_model = x_train[:, feature_indices]
        x_test_model = x_test[:, feature_indices]

        pipeline = make_xgboost_pipeline()
        pipeline.fit(x_train_model, y_train)

        probabilities = pipeline.predict_proba(x_test_model)[:, 1]

        model_metrics = calculate_metrics(
            y_test,
            probabilities,
            label=model_label,
        )

        trained_models[model_key] = {
            "pipeline": pipeline,
            "features": feature_names,
            "indices": feature_indices,
        }

        test_probabilities[model_key] = probabilities
        test_metrics[model_key] = model_metrics

        joblib.dump(
            pipeline,
            MODELS_DIR / f"phase15_model_{model_key}.pkl",
        )

        print(
            f"    AUC={model_metrics['AUC_ROC']:.3f}  "
            f"PR={model_metrics['AUC_PR']:.3f}  "
            f"F1={model_metrics['F1']:.3f}  "
            f"Sens={model_metrics['Sensitivity']:.3f}  "
            f"Spec={model_metrics['Specificity']:.3f}  "
            f"MCC={model_metrics['MCC']:.3f}  "
            f"Brier={model_metrics['Brier']:.4f}"
        )

    return trained_models, test_probabilities, test_metrics


def save_bootstrap_results(y_test, test_probabilities, model_configs):
    section("STEP 3 - Bootstrap 95% CI")

    rows = []

    for model_key, probabilities in test_probabilities.items():
        model_label = model_configs[model_key]["label"]

        ci = bootstrap_ci(
            y_test,
            probabilities,
            n_boot=1000,
        )

        print(f"\n  {model_label}")

        for metric_name, (mean_value, ci_low, ci_high) in ci.items():
            print(
                f"    {metric_name:<14} "
                f"{mean_value:.3f}  [{ci_low:.3f}, {ci_high:.3f}]"
            )

            rows.append(
                {
                    "model": model_label,
                    "metric": metric_name,
                    "mean": mean_value,
                    "CI_lo": ci_low,
                    "CI_hi": ci_high,
                }
            )

    pd.DataFrame(rows).to_csv(
        RESULTS_DIR / "phase15_bootstrap_ci.csv",
        index=False,
    )

    print("\n  Saved: phase15_bootstrap_ci.csv")


