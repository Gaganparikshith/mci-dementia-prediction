def save_shap_importance(x_test, trained_models, model_configs):
    section("STEP 6 - SHAP feature importance")

    shap_rows = []

    for model_key, model_info in trained_models.items():
        pipeline = model_info["pipeline"]
        feature_names = model_info["features"]
        feature_indices = model_info["indices"]
        model_label = model_configs[model_key]["label"]

        print(f"\n  {model_label}")

        x_test_model = x_test[:, feature_indices]
        x_test_processed = preprocess_for_shap(
            pipeline,
            x_test_model,
        )

        try:
            xgb_model = pipeline.named_steps["clf"]

            explainer = shap.TreeExplainer(xgb_model)
            raw_shap_values = explainer.shap_values(x_test_processed)
            shap_values = safe_shap_values(raw_shap_values)

            mean_abs_shap = np.abs(shap_values).mean(axis=0)
            importance_order = np.argsort(mean_abs_shap)[::-1]

            print("  Top features by mean |SHAP|:")

            for rank, feature_index in enumerate(importance_order[:10], start=1):
                print(
                    f"    {rank:>2}. "
                    f"{feature_names[feature_index]:<28} "
                    f"{mean_abs_shap[feature_index]:.4f}"
                )

                shap_rows.append(
                    {
                        "model": model_label,
                        "rank": rank,
                        "feature": feature_names[feature_index],
                        "mean_abs_shap": mean_abs_shap[feature_index],
                    }
                )

            top10_indices = importance_order[:10]

            plt.figure(figsize=(8, 5))

            plt.barh(
                [feature_names[index] for index in reversed(top10_indices)],
                [mean_abs_shap[index] for index in reversed(top10_indices)],
                color="#2563EB",
                alpha=0.85,
            )

            plt.xlabel("Mean |SHAP value|", fontsize=11)
            plt.title(f"SHAP Importance - {model_label}", fontsize=12)

            plt.tight_layout()

            safe_key = model_key.replace(" ", "_")

            plt.savefig(
                PLOTS_DIR / f"phase15_shap_{safe_key}.png",
                **PLOT_KW,
            )

            plt.close()

            print(f"  Saved: phase15_shap_{safe_key}.png")

        except Exception as error:
            print(f"  SHAP failed for {model_label}: {error}")

    pd.DataFrame(shap_rows).to_csv(
        RESULTS_DIR / "phase15_shap_importance.csv",
        index=False,
    )

    print("\n  Saved: phase15_shap_importance.csv")


