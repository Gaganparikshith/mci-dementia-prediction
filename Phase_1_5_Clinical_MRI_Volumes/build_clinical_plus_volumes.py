#!/usr/bin/env python3
"""
README - build_clinical_plus_volumes.py
=======================================

This script builds the Phase 1.5 clinical + MRI volumetric dataset.

It merges the Phase 1 clinical metadata file with selected MRI volumetric
features extracted from UCSFFSX7_21May2026.csv.

The final output is saved as:

final_metadata_clinical_plus_volumes.csv

This file is used for Phase 1.5 experiments, where clinical features are
combined with FreeSurfer-derived MRI volumetric features.

Input files
-----------
final_metadata.csv
    Clinical-only metadata generated by build_dataset.py.

UCSFFSX7_21May2026.csv
    ADNI FreeSurfer volumetric file containing brain-region volume features.

Output file
-----------
final_metadata_clinical_plus_volumes.csv
    Clinical metadata merged with MRI volumetric features.

Confirmed UCSFFSX7 column mapping
---------------------------------
ST124SV  -> Hippocampus_L
ST88SV   -> Hippocampus_R
ST26CV   -> Entorhinal_L
ST32CV   -> Fusiform_L
ST48CV   -> MidTemporal_L
ST97CV   -> MidTemporal_R
ST75SV   -> Amygdala_R

Additional fallback features are searched using keyword patterns.

Fixes included
--------------
1. has_data() safely handles both scalar values and arrays.
2. Correct ST suffixes are used:
   SV for subcortical volumes.
   CV for cortical volumes.
3. DATA_DIR points directly to the DATA folder.

Run
---
python build_clinical_plus_volumes.py

Next step
---------
python training/train_clinical_plus_volumes.py
"""

import re
from pathlib import Path

import numpy as np
import pandas as pd


# Paths
DATA_DIR = Path(r"C:\Users\ASUS\Desktop\Research Resources\DATA")

META_DIR = Path(
    r"C:\Users\ASUS\Desktop\Research Resources"
    r"\DementiaResearch\data\metadata"
)

CLINICAL_FILE = META_DIR / "final_metadata.csv"
OUTPUT_FILE = META_DIR / "final_metadata_clinical_plus_volumes.csv"

META_DIR.mkdir(parents=True, exist_ok=True)


# Confirmed UCSFFSX7 column mapping
CONFIRMED_MAP = {
    "Hippocampus_L": "ST124SV",
    "Hippocampus_R": "ST88SV",
    "Entorhinal_L": "ST26CV",
    "Fusiform_L": "ST32CV",
    "MidTemporal_L": "ST48CV",
    "MidTemporal_R": "ST97CV",
    "Amygdala_R": "ST75SV",
}


# Fallback pattern search for additional useful volumetric features
FALLBACK_PATTERNS = {
    "ICV": [
        r"^ICV$",
        r"INTRA",
        r"eTIV",
        r"ESTINTCRANVOL",
    ],
    "Ventricles": [
        r"ST14SV",
        r"LATVENT",
    ],
    "WholeBrain": [
        r"ST162SV",
        r"WHOLEBR",
        r"BrainSegVol",
    ],
    "Entorhinal_R": [
        r"ST75CV",
        r"RENTOR",
    ],
    "Fusiform_R": [
        r"ST81CV",
        r"RFUSIF",
    ],
}


def section(title):
    print()
    print("=" * 62)
    print(f"  {title}")
    print("=" * 62)


def find_column(columns, patterns):
    """Find the first column matching any of the given regex patterns."""
    for pattern in patterns:
        for column in columns:
            if re.search(pattern, column, re.IGNORECASE):
                return column

    return None


def has_data(values):
    """
    Return True if the input contains at least one non-NaN value.

    This function is safe for both scalar values and array-like values.
    """
    if values is None:
        return False

    if np.isscalar(values):
        return not bool(pd.isna(values))

    values = np.asarray(values, dtype=float)

    return bool(np.any(~np.isnan(values)))


def load_clinical_metadata():
    section("STEP 1 - Loading clinical metadata")

    clinical_df = pd.read_csv(CLINICAL_FILE)

    clinical_df["RID"] = pd.to_numeric(
        clinical_df["RID"],
        errors="coerce",
    ).astype("Int64")

    p_count = int((clinical_df["LABEL"] == 1).sum())
    s_count = int((clinical_df["LABEL"] == 0).sum())

    print(
        f"  Clinical subjects: {len(clinical_df):,} "
        f"(pMCI={p_count}, sMCI={s_count})"
    )

    return clinical_df


def find_ucsffsx7_file():
    ucsf_path = DATA_DIR / "UCSFFSX7_21May2026.csv"

    if ucsf_path.exists():
        return ucsf_path

    candidates = list(DATA_DIR.glob("UCSFFSX7*.csv"))

    if candidates:
        return candidates[0]

    raise FileNotFoundError(f"UCSFFSX7*.csv not found in {DATA_DIR}")


def load_ucsffsx7_data():
    section("STEP 2 - Loading UCSFFSX7 volumetrics")

    ucsf_path = find_ucsffsx7_file()

    print(f"  File: {ucsf_path.name}")

    fs_df = pd.read_csv(
        ucsf_path,
        low_memory=False,
    )

    print(f"  Rows: {len(fs_df):,}  Cols: {fs_df.shape[1]}")

    fs_df = keep_baseline_rows(fs_df)

    fs_df = add_or_fix_rid(fs_df)

    print(f"  Unique RIDs: {fs_df['RID'].nunique():,}")

    return fs_df


def keep_baseline_rows(fs_df):
    """
    Keep baseline-like rows if VISCODE or VISCODE2 is available.

    Accepted baseline visit codes:
    bl, sc, m00
    """
    for visit_col in ["VISCODE", "VISCODE2"]:
        if visit_col not in fs_df.columns:
            continue

        visit_values = fs_df[visit_col].astype(str).str.strip().str.lower()

        baseline_mask = visit_values.isin(
            {
                "bl",
                "sc",
                "m00",
            }
        )

        baseline_df = fs_df[baseline_mask].copy()

        if len(baseline_df) > 100:
            print(f"  Baseline rows ({visit_col}): {len(baseline_df):,}")
            return baseline_df

    return fs_df


def add_or_fix_rid(fs_df):
    """
    Ensure the FreeSurfer dataframe has a numeric RID column.

    If RID is missing but PTID is available, RID is extracted from PTID.
    """
    fs_df = fs_df.copy()

    if "RID" not in fs_df.columns and "PTID" in fs_df.columns:
        fs_df["RID"] = fs_df["PTID"].apply(
            lambda value: int(str(value).split("_")[-1])
            if pd.notna(value)
            else np.nan
        )

    fs_df["RID"] = pd.to_numeric(
        fs_df["RID"],
        errors="coerce",
    ).astype("Int64")

    return fs_df


def extract_confirmed_volumes(fs_df, rows):
    print("  Confirmed exact-match columns:")

    for target_name, source_column in CONFIRMED_MAP.items():
        if source_column in fs_df.columns:
            values = pd.to_numeric(
                fs_df[source_column],
                errors="coerce",
            ).values

            rows[target_name] = values

            non_null_count = int(np.sum(~np.isnan(values)))

            print(
                f"    {target_name:<20} <- {source_column:<12} "
                f"({non_null_count:,} non-null)"
            )

        else:
            rows[target_name] = np.full(len(fs_df), np.nan)

            print(
                f"    {target_name:<20}    {source_column:<12} "
                f"NOT FOUND"
            )

    return rows


def extract_fallback_volumes(fs_df, rows):
    print("\n  Fallback pattern-search columns:")

    for target_name, patterns in FALLBACK_PATTERNS.items():
        matched_column = find_column(
            fs_df.columns,
            patterns,
        )

        if matched_column:
            values = pd.to_numeric(
                fs_df[matched_column],
                errors="coerce",
            ).values

            rows[target_name] = values

            non_null_count = int(np.sum(~np.isnan(values)))

            print(
                f"    {target_name:<20} <- {matched_column:<20} "
                f"({non_null_count:,} non-null)"
            )

        else:
            rows[target_name] = np.full(len(fs_df), np.nan)

            print(f"    {target_name:<20}    not found")

    return rows


def build_volume_table(fs_df):
    section("STEP 3 - Extracting volume columns")

    rows = {
        "RID": fs_df["RID"].values,
    }

    rows = extract_confirmed_volumes(
        fs_df,
        rows,
    )

    rows = extract_fallback_volumes(
        fs_df,
        rows,
    )

    volume_df = pd.DataFrame(rows)
    volume_df = volume_df.drop_duplicates("RID")

    print(f"\n  Volume table: {len(volume_df):,} unique subjects")

    return volume_df


def add_hippocampal_features(volume_df):
    if not (
        has_data(volume_df["Hippocampus_L"].values)
        and has_data(volume_df["Hippocampus_R"].values)
    ):
        return volume_df

    volume_df["Hippocampus_total"] = (
        volume_df["Hippocampus_L"] + volume_df["Hippocampus_R"]
    )

    denominator = volume_df["Hippocampus_total"].replace(0, np.nan)

    volume_df["Hippocampus_asymmetry"] = (
        volume_df["Hippocampus_R"] - volume_df["Hippocampus_L"]
    ) / denominator

    non_null_count = int(volume_df["Hippocampus_total"].notna().sum())

    print(f"  Hippocampus_total / asymmetry ({non_null_count:,} non-null)")

    return volume_df


def add_icv_ratio(volume_df):
    if has_data(volume_df["ICV"].values) and "Hippocampus_total" in volume_df.columns:
        volume_df["Hippocampus_ICV_ratio"] = (
            volume_df["Hippocampus_total"]
            / volume_df["ICV"].replace(0, np.nan)
        )

        print("  Hippocampus_ICV_ratio")

    else:
        print("  Hippocampus_ICV_ratio - skipped because ICV was not available")

    return volume_df


def add_bilateral_mean_features(volume_df):
    bilateral_pairs = [
        (
            "Entorhinal_L",
            "Entorhinal_R",
            "Entorhinal_mean",
        ),
        (
            "Fusiform_L",
            "Fusiform_R",
            "Fusiform_mean",
        ),
        (
            "MidTemporal_L",
            "MidTemporal_R",
            "MidTemporal_mean",
        ),
    ]

    for left_col, right_col, output_col in bilateral_pairs:
        left_available = (
            left_col in volume_df.columns
            and has_data(volume_df[left_col].values)
        )

        right_available = (
            right_col in volume_df.columns
            and has_data(volume_df[right_col].values)
        )

        if left_available and right_available:
            volume_df[output_col] = (
                volume_df[left_col] + volume_df[right_col]
            ) / 2

            print(f"  {output_col:<28} = (L + R) / 2")

        elif left_available:
            volume_df[output_col] = volume_df[left_col]

            print(f"  {output_col:<28} = L only")

    return volume_df


def add_derived_volume_features(volume_df):
    section("STEP 4 - Derived volume features")

    volume_df = add_hippocampal_features(volume_df)
    volume_df = add_icv_ratio(volume_df)
    volume_df = add_bilateral_mean_features(volume_df)

    return volume_df


def merge_clinical_and_volumes(clinical_df, volume_df):
    section("STEP 5 - Merging clinical and volume features")

    merged_df = clinical_df.merge(
        volume_df,
        on="RID",
        how="left",
    )

    print(f"  Shape: {merged_df.shape}")

    volume_columns = [
        column
        for column in merged_df.columns
        if column not in clinical_df.columns
    ]

    usable_columns = []

    print(f"\n  {'Feature':<28} {'N present':>10}   {'Coverage':>9}")
    print("  " + "-" * 52)

    for feature in volume_columns:
        present_count = int(merged_df[feature].notna().sum())
        coverage = present_count / len(merged_df)

        flag = "  <- LOW" if coverage < 0.10 else ""

        print(
            f"  {feature:<28} {present_count:>10}   "
            f"{coverage * 100:>8.1f}%{flag}"
        )

        if coverage >= 0.10:
            usable_columns.append(feature)

    print(f"\n  Usable volume features, >=10% coverage: {len(usable_columns)}")
    print(f"  {usable_columns}")

    return merged_df


def save_output(merged_df):
    section("STEP 6 - Saving output")

    merged_df.to_csv(
        OUTPUT_FILE,
        index=False,
    )

    if "Hippocampus_L" in merged_df.columns:
        hippocampus_count = int(merged_df["Hippocampus_L"].notna().sum())
    else:
        hippocampus_count = 0

    hippocampus_coverage = hippocampus_count / len(merged_df) * 100

    print(
        f"  Saved: {OUTPUT_FILE.name} "
        f"({merged_df.shape[0]} rows x {merged_df.shape[1]} cols)"
    )

    print(
        f"  Subjects with hippocampus volume: "
        f"{hippocampus_count:,} / {len(merged_df):,} "
        f"({hippocampus_coverage:.1f}%)"
    )

    print("\n  Next: python training/train_clinical_plus_volumes.py")


def main():
    clinical_df = load_clinical_metadata()

    fs_df = load_ucsffsx7_data()

    volume_df = build_volume_table(fs_df)

    volume_df = add_derived_volume_features(volume_df)

    merged_df = merge_clinical_and_volumes(
        clinical_df,
        volume_df,
    )

    save_output(merged_df)


if __name__ == "__main__":
    main()