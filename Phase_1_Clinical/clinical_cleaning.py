"""
README - clinical_cleaning.py
=============================

This script cleans and imputes the Phase 1 clinical-only dataset.

It uses final_metadata.csv, which is generated by build_dataset.py. The main
purpose of this script is to validate clinical feature ranges, create or load
train/validation/test splits, and perform imputation without data leakage.

Important
---------
Imputation is fitted only on the training split.

The fitted imputers are then applied to the validation and test splits. This
ensures that validation and test data are not used while learning imputation
values, which prevents data leakage.

What this script does
---------------------
1. Loads final_metadata.csv.
2. Checks and fixes PTGENDER encoding if needed.
3. Marks out-of-range clinical values as NaN.
4. Loads existing train/validation/test splits.
5. Creates stratified splits if split files are not found.
6. Fits KNN and median imputers only on training data.
7. Applies the fitted imputers to validation and test data.
8. Recomputes derived clinical features after imputation.
9. Saves cleaned train, validation, and test CSV files.

Imputation strategy
-------------------
KNN imputation
    Used for features with less than or equal to 30% missingness in the
    training split.

Median imputation
    Used for features with more than 30% missingness in the training split.

Run
---
python Scripts/preprocessing/clinical_cleaning.py

Next step
---------
python Scripts/training/train_clinical.py
"""

import os
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.impute import KNNImputer, SimpleImputer
from sklearn.model_selection import StratifiedShuffleSplit


sys.path.insert(0, str(Path(__file__).resolve().parents[2]))


# Paths
ROOT = r"C:\Users\ASUS\Desktop\Research Resources\DementiaResearch"

METADATA_CSV = os.path.join(ROOT, "data", "metadata", "final_metadata.csv")
SPLITS_DIR = os.path.join(ROOT, "data", "splits")
OUT_DIR = os.path.join(ROOT, "data", "metadata")


# Phase 1 E4 clinical feature set
E4_FEATURES = [
    "PTGENDER",
    "PTEDUCAT",
    "MMSE_BL",
    "FAQ_BL",
    "GDS_BL",
    "MOCA_BL",
    "ADAS11_BL",
    "ADAS13_BL",
    "RAVLT_immediate",
    "RAVLT_forgetting",
    "RAVLT_delayed",
    "RAVLT_forget_rate",
    "DigitSpan",
    "TrailsB",
    "MMSE_FAQ_composite",
    "ADAS_MMSE_gap",
    "CDRSB_BL",
    "CDR_GLOBAL_BL",
]

TARGET = "LABEL"


# Valid clinical ranges.
# Values outside these ranges are converted to NaN before imputation.
VALID_RANGES = {
    "MMSE_BL": (0, 30),
    "FAQ_BL": (0, 30),
    "GDS_BL": (0, 15),
    "MOCA_BL": (0, 30),
    "ADAS11_BL": (0, 70),
    "ADAS13_BL": (0, 85),
    "RAVLT_immediate": (0, 75),
    "RAVLT_forgetting": (0, 15),
    "RAVLT_delayed": (0, 15),
    "RAVLT_forget_rate": (0, 1),
    "CDRSB_BL": (0, 18),
    "CDR_GLOBAL_BL": (0, 3),
    "PTEDUCAT": (0, 20),
}


def sec(title):
    print(f"\n{'-' * 62}")
    print(f"  {title}")
    print(f"{'-' * 62}")


def load_metadata():
    sec("STEP 1 - Loading final_metadata.csv")

    df = pd.read_csv(METADATA_CSV)

    print(f"  Shape  : {df.shape}")
    print(f"  pMCI   : {(df[TARGET] == 1).sum()}  sMCI: {(df[TARGET] == 0).sum()}")

    return df


def fix_gender_encoding(df):
    print(f"\n  PTGENDER value counts: {df['PTGENDER'].value_counts().to_dict()}")

    # build_dataset.py should already map:
    # 1 -> 0 Male
    # 2 -> 1 Female
    unique_values = set(df["PTGENDER"].dropna().unique())

    if unique_values == {1.0, 2.0}:
        df["PTGENDER"] = df["PTGENDER"].map({1: 0, 2: 1})
        print("  PTGENDER remapped: 1 -> 0 Male, 2 -> 1 Female")
    else:
        print("  PTGENDER already 0/1 - no change needed")

    return df


def validate_ranges(df):
    sec("STEP 2 - Range validation")

    for col, (low, high) in VALID_RANGES.items():
        if col not in df.columns:
            continue

        bad_mask = (df[col] < low) | (df[col] > high)
        bad_count = bad_mask.sum()

        if bad_count > 0:
            df.loc[bad_mask, col] = np.nan
            print(f"  {col:<25} {bad_count} out-of-range values -> NaN")

    print("  Range validation complete.")

    return df


def load_or_create_splits(df):
    sec("STEP 3 - Loading train/val/test splits")

    train_path = os.path.join(SPLITS_DIR, "train.csv")
    val_path = os.path.join(SPLITS_DIR, "val.csv")
    test_path = os.path.join(SPLITS_DIR, "test.csv")

    split_files_exist = all(
        Path(path).exists()
        for path in [train_path, val_path, test_path]
    )

    if split_files_exist:
        train_rids = pd.read_csv(train_path)["RID"].tolist()
        val_rids = pd.read_csv(val_path)["RID"].tolist()
        test_rids = pd.read_csv(test_path)["RID"].tolist()

        print(
            f"  Loaded splits: train={len(train_rids)} "
            f"val={len(val_rids)} test={len(test_rids)}"
        )

    else:
        print("  Splits not found - creating 70/10/20 stratified split now...")

        os.makedirs(SPLITS_DIR, exist_ok=True)

        first_split = StratifiedShuffleSplit(
            n_splits=1,
            test_size=0.20,
            random_state=42,
        )

        train_val_idx, test_idx = next(first_split.split(df, df[TARGET]))

        train_val_df = df.iloc[train_val_idx]
        test_df = df.iloc[test_idx]

        second_split = StratifiedShuffleSplit(
            n_splits=1,
            test_size=0.125,
            random_state=42,
        )

        train_idx, val_idx = next(
            second_split.split(train_val_df, train_val_df[TARGET])
        )

        train_df = train_val_df.iloc[train_idx]
        val_df = train_val_df.iloc[val_idx]

        train_rids = train_df["RID"].tolist()
        val_rids = val_df["RID"].tolist()
        test_rids = test_df["RID"].tolist()

        pd.DataFrame({"RID": train_rids}).to_csv(train_path, index=False)
        pd.DataFrame({"RID": val_rids}).to_csv(val_path, index=False)
        pd.DataFrame({"RID": test_rids}).to_csv(test_path, index=False)

        print(
            f"  Splits saved: train={len(train_rids)} "
            f"val={len(val_rids)} test={len(test_rids)}"
        )

    train_df = df[df["RID"].isin(train_rids)].copy()
    val_df = df[df["RID"].isin(val_rids)].copy()
    test_df = df[df["RID"].isin(test_rids)].copy()

    print(
        f"\n  Train pMCI={int((train_df[TARGET] == 1).sum())} "
        f"sMCI={int((train_df[TARGET] == 0).sum())}"
    )

    print(
        f"  Val   pMCI={int((val_df[TARGET] == 1).sum())} "
        f"sMCI={int((val_df[TARGET] == 0).sum())}"
    )

    print(
        f"  Test  pMCI={int((test_df[TARGET] == 1).sum())} "
        f"sMCI={int((test_df[TARGET] == 0).sum())}"
    )

    return train_df, val_df, test_df


def report_train_missingness(train_df, features):
    print("\n  Pre-imputation missingness in train set:")
    print(f"  {'Feature':<28} {'Missing':>8}  {'%':>6}")
    print(f"  {'-' * 44}")

    for col in features:
        missing_count = train_df[col].isna().sum()
        missing_pct = 100 * missing_count / len(train_df)

        flag = "  <- HIGH" if missing_pct > 30 else ""

        print(f"  {col:<28} {missing_count:>8}  {missing_pct:>5.1f}%{flag}")


def impute_features(train_df, val_df, test_df):
    sec("STEP 4 - KNN Imputation fitted on train only")

    impute_features = [
        feature
        for feature in E4_FEATURES
        if feature in train_df.columns and feature != "PTGENDER"
    ]

    report_train_missingness(train_df, impute_features)

    missing_pct = train_df[impute_features].isna().mean()

    knn_features = [
        feature
        for feature in impute_features
        if missing_pct[feature] <= 0.30
    ]

    median_features = [
        feature
        for feature in impute_features
        if missing_pct[feature] > 0.30
    ]

    print(f"\n  KNN impute k=5 : {knn_features}")
    print(f"  Median impute  : {median_features}")

    if knn_features:
        knn_imputer = KNNImputer(n_neighbors=5)

        train_df[knn_features] = knn_imputer.fit_transform(train_df[knn_features])
        val_df[knn_features] = knn_imputer.transform(val_df[knn_features])
        test_df[knn_features] = knn_imputer.transform(test_df[knn_features])

        print("\n  KNN imputer fitted on train -> applied to val and test")

    if median_features:
        median_imputer = SimpleImputer(strategy="median")

        train_df[median_features] = median_imputer.fit_transform(train_df[median_features])
        val_df[median_features] = median_imputer.transform(val_df[median_features])
        test_df[median_features] = median_imputer.transform(test_df[median_features])

        print("  Median imputer fitted on train -> applied to val and test")

    for split_name, split_df in [
        ("train", train_df),
        ("val", val_df),
        ("test", test_df),
    ]:
        available_features = [
            feature
            for feature in E4_FEATURES
            if feature in split_df.columns
        ]

        remaining_nulls = split_df[available_features].isna().sum().sum()

        print(f"  {split_name}: remaining NaNs in E4 features = {remaining_nulls}")

    return train_df, val_df, test_df


def add_derived_features(df):
    if {"MMSE_BL", "FAQ_BL"}.issubset(df.columns):
        df["MMSE_FAQ_composite"] = (30 - df["MMSE_BL"]) + df["FAQ_BL"]

    if {"ADAS11_BL", "MMSE_BL"}.issubset(df.columns):
        df["ADAS_MMSE_gap"] = df["ADAS11_BL"] - (30 - df["MMSE_BL"])

    if {"RAVLT_forgetting", "RAVLT_immediate"}.issubset(df.columns):
        denominator = df["RAVLT_immediate"].replace(0, np.nan)
        df["RAVLT_forget_rate"] = (df["RAVLT_forgetting"] / denominator).clip(0, 1)

    return df


def recompute_derived_features(train_df, val_df, test_df):
    sec("STEP 5 - Recomputing derived features after imputation")

    train_df = add_derived_features(train_df)
    val_df = add_derived_features(val_df)
    test_df = add_derived_features(test_df)

    print("  Derived features recomputed on all three splits.")

    return train_df, val_df, test_df


def save_cleaned_splits(train_df, val_df, test_df):
    sec("STEP 6 - Saving cleaned splits")

    os.makedirs(OUT_DIR, exist_ok=True)

    train_out = os.path.join(OUT_DIR, "train_clean.csv")
    val_out = os.path.join(OUT_DIR, "val_clean.csv")
    test_out = os.path.join(OUT_DIR, "test_clean.csv")

    train_df.to_csv(train_out, index=False)
    val_df.to_csv(val_out, index=False)
    test_df.to_csv(test_out, index=False)

    print(f"  train_clean.csv  {train_df.shape}  -> {train_out}")
    print(f"  val_clean.csv    {val_df.shape}    -> {val_out}")
    print(f"  test_clean.csv   {test_df.shape}   -> {test_out}")


def print_final_summary(train_df, val_df, test_df):
    sec("CLEANING COMPLETE")

    available_features = [
        feature
        for feature in E4_FEATURES
        if feature in train_df.columns
    ]

    print(
        f"""
  Subjects  : train={len(train_df)}  val={len(val_df)}  test={len(test_df)}
  E4 feats  : {len(available_features)} / {len(E4_FEATURES)} available
  Imputation: KNN k=5 for <=30% missing, Median for >30% missing
  Leakage   : NONE - imputer fitted on train only

  PTGENDER encoding:
    0 = Male
    1 = Female

  Next:  python Scripts/training/train_clinical.py
"""
    )


def main():
    df = load_metadata()
    df = fix_gender_encoding(df)
    df = validate_ranges(df)

    train_df, val_df, test_df = load_or_create_splits(df)

    train_df, val_df, test_df = impute_features(train_df, val_df, test_df)

    train_df, val_df, test_df = recompute_derived_features(
        train_df,
        val_df,
        test_df,
    )

    save_cleaned_splits(train_df, val_df, test_df)

    print_final_summary(train_df, val_df, test_df)


if __name__ == "__main__":
    main()